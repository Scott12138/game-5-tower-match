def main():
    out = []
    out.append("SFX = {")
    cur = None
    head = {
        'tile': ('① 麻将落槽 —— 全部来自「効果音ラボ」（免费商用·免署名），标题与用途说明逐字取自下载页；'
                 '优先选「硬物相碰」的听感：麻将牌是硬塑料/亚克力，磕在木桌上应当是短、干、脆。'),
        'win':  ('② 胜利 —— 一条上行收束，2~3 秒，欢快但不铺张；'
                 '与失败共用同一套语汇（综艺答题/游戏升级），保证胜败成对。'),
        'lose': ('③ 失败 —— 休闲游戏最忌"重挫感"：要下行、要软、最好还有点喜感；'
                 '刻意避开刺耳蜂鸣与长篇悲鸣。'),
    }
    for cat, fn, cn, jp, note in SPEC:
        if cat != cur:
            cur = cat
            out.append(f'    # {"="*56}')
            # ★ head 里可能含换行（多句说明）→ 必须逐行加 '#'，
            #   否则第二行会变成裸文本，直接语法错误
            for ln in head[cat].split('\n'):
                out.append(f'    #  {ln.strip()}')
            out.append(f'    # {"="*56}')
        title, desc, page_cat = META[fn]
        out.append(f"    '{cat}-{fn}': dict(")
        out.append(f"        cat='{cat}', title='{cn}｜{title}', artist='効果音ラボ',")
        out.append(f"        src='soundeffect-lab.info',")
        out.append(f"        official='「{title}」— {desc}（{page_cat} 分类）',")
        out.append(f"        tags='{jp}',")
        out.append(f"        note='{note}',")
        out.append(f"        file='{LAB}/{page_cat}/mp3/{fn}.mp3',")
        out.append(f"        page='{LAB}/{page_cat}/'),")
    out.append("}")
    block = '\n'.join(out) + '\n'

    p = os.path.join(HERE, 'r44-fetch.py')
    s = io.open(p, encoding='utf-8').read()
    i = s.index('SFX = {')
    j = s.index('def dl(', i)
    s = s[:i] + block + '\n\n' + s[j:]
    io.open(p, 'w', encoding='utf-8').write(s)
    n = block.count("': dict(")
    print(f'已写入 {n} 条音效目录 → r44-fetch.py')


if __name__ == '__main__':
    main()
