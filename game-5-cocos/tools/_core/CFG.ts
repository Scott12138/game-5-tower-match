// ============================================================
//  六·六、难度参数（★ 第 46 轮新增 · 用户需求⑥）
// ============================================================
//  【用户原话】「目前构建的关卡难度太低了，用户基本不需要看广告，这会影响我的收益，
//   请设置一个难度参数，根据难度参数来调整牌的顺序以控制关卡难度，后续我可以对参数进行调节」。
//
//  【为什么难度会低 —— 根因】关卡生成器 `level_design.py` 里那句
//    `faces = fill_by_triples(order, seed)`：它把「贪心可点剥离序」**按每 3 张一切、
//    每一段填同一种牌面**。于是最优解退化成"顺着能点的往下点，点到的三张天然是一组"——
//    玩家几乎不用思考、不需要道具，自然也就不会有广告。
//
//  【本参数做什么】在**运行期**把牌面按这个顺序结构打散（实现见 `core/Difficulty.ts`）：
//    把清序按 `BLOCK` 大小切成连续块，**只在块内**把牌面洗一遍。
//    **只换牌面、不动几何** —— 牌的 x/y/层号/朝向一个像素都不变 ⇒
//    桌面长相、覆盖结构、"看着能点就能点"全不受影响。
//
//  【★ 旋钮的刻度】`BLOCK`（整数，越大越难）**就是难度参数**：
//    · `3`  = 生成器一组的长度 ⇒ 块内洗牌是**恒等变换** ⇒ 完全按关卡表原样（本轮之前）
//    · `4~6` = 实测"照清序点"仍 **30/30 通关** ⇒ **有解是被构造性证明的**（不是靠感觉）
//    · `6`  = **当前默认档**（实测 · 6 种子均值）：
//             无脑通关 13.8/30 · 会看牌 26.7/30 · 照清序 30/30 · 槽内峰值 4
//    · `7~8` = 开始偶发失去保证（29.8 / 29.3 关）—— 跨块残牌叠加会把槽顶到 8 = 上限
//    · `≥10` = 可解性明显被破坏（17.5 → 1.7/30），**不建议**
//  ⚠️ 完整标定表（档位 ↔ 三种代理玩家的通关率）用下面这条命令重跑，改完请把表贴回记录：
//    `python3 tools/sync-core.py && node --experimental-strip-types --no-warnings tools/_r46-diff-verify.mjs`
//
//  ⚠️ 置换**只在块内洗牌**，牌面多重集逐张守恒 ⇒ "每种牌面张数是 3 的倍数"仍然成立。
//    难度升高的是**顺序**，不是"根本清不掉"。
export const DIFF = {
    /** 关掉 = 完全按 `LevelData.ts` 的原样牌面（等价于 `BLOCK = 3`，留作总开关） */
    ENABLED: true,
    /** ★ 难度参数：清序上的**块大小**。3 = 原样；建议 **4~6**；≥7 起失去"可解"保证 */
    BLOCK: 6,
    /** 单关覆盖（key = 关卡号 1~30，1-based）；写了就用它、没写用 `BLOCK` */
    PER_LEVEL: {} as Record<number, number>,
    /** 随机种子；0 = 按关卡号派生（同一关每次进局都一样，便于复现与截图对账） */
    SEED: 0,
};

/** 取第 `lv` 关（1-based）的难度块大小 */
export function diffBlockOf(lv: number): number {
    if (!DIFF.ENABLED) return 3;
    const per = DIFF.PER_LEVEL[lv];
    const b = typeof per === 'number' ? per : DIFF.BLOCK;
    return Math.max(3, Math.round(b));
}

/** 取第 `lv` 关的置换种子（0 ⇒ 按关卡号派生） */
export function diffSeedOf(lv: number): number {
    return DIFF.SEED ? (DIFF.SEED + lv * 7919) : (lv * 2654435761);
}

